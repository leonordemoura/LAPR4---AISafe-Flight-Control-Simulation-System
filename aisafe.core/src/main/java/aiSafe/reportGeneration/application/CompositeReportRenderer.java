package aiSafe.reportGeneration.application;

import aiSafe.reportGeneration.domain.Report;
import aiSafe.reportGeneration.domain.ReportRenderer;

import java.util.Arrays;
import java.util.Objects;

/**
 * Composite implementation of the {@link ReportRenderer} interface that delegates rendering to multiple underlying renderers. This allows for generating multiple output formats (e.g., PDF, HTML) from the same report data in a single operation. The first renderer in the provided array is considered the primary renderer, and its output file path will be returned by the {@code render} method.
 * @see ReportRenderer
 * @author 2DE - Group 3
 * @version 2.0
 */
public class CompositeReportRenderer implements ReportRenderer {

    /** The array of renderers to which rendering will be delegated. The first renderer is considered the primary renderer. */
    private final ReportRenderer[] renderers;

    /**
     * Constructs a composite renderer that delegates to the given array of renderers. The first renderer in the array is considered the primary renderer, and its output file path will be returned by the {@code render} method. All renderers will be invoked in the order they are provided.
     * @param renderers
     */
    public CompositeReportRenderer(final ReportRenderer... renderers) {
        if (renderers == null || renderers.length == 0) {
            throw new IllegalArgumentException("At least one renderer is required.");
        }
        this.renderers = Arrays.copyOf(renderers, renderers.length);
    }

    /**
     * Renders the given report using all configured renderers and returns the path of the primary output file (the one generated by the first renderer).
     * @param report          the fully-assembled report to render (never {@code null})
     * @param outputDirectory the filesystem path of the target directory (never {@code null})
     * @return the absolute path of the primary file that was written
     * @throws IllegalArgumentException if the file cannot be created or written by any of the renderers
     */
    @Override
    public String render(final Report report, final String outputDirectory) {
        Objects.requireNonNull(report, "Report cannot be null.");
        Objects.requireNonNull(outputDirectory, "Output directory cannot be null.");

        String primaryPath = null;
        for (final ReportRenderer renderer : renderers) {
            final String path = renderer.render(report, outputDirectory);
            if (primaryPath == null) {
                primaryPath = path;
            }
        }
        return primaryPath;
    }
}
