package aiSafe.reportGeneration.domain;

import jakarta.persistence.Embeddable;

import java.time.LocalDateTime;

/**
 * Represents the header information of a generated report, including the generation timestamp and the user responsible for generating the report.
 */
@Embeddable
public class ReportHeader {
    private LocalDateTime generatedAt;
    private String generatedBy;

    /** Default constructor for ORM. */
    protected ReportHeader() {
        // for ORM
    }

    /** Constructs a new ReportHeader with the specified generation timestamp and user. */
    private ReportHeader(LocalDateTime generatedAt, String generatedBy) {
        if (generatedAt == null) {
            throw new IllegalArgumentException("Generated at cannot be null.");
        }
        if (generatedBy == null || generatedBy.trim().isEmpty()) {
            throw new IllegalArgumentException("Generated by cannot be null or empty.");
        }
        this.generatedAt = generatedAt;
        this.generatedBy = generatedBy;
    }

    /**
    * Creates a new ReportHeader instance with the specified generation timestamp and user.
    * @param generatedAt the date and time when the report was generated
    * @param generatedBy the name of the user who generated the report
    * @return a new ReportHeader instance with the specified generation information
    */
    public static ReportHeader valueOf(LocalDateTime generatedAt, String generatedBy) {
        return new ReportHeader(generatedAt, generatedBy);
    }

    /** Returns the date and time when the report was generated. */
    public LocalDateTime generatedAt() {
        return generatedAt;
    }

    /** Returns the name of the user who generated the report. */
    public String generatedBy() {
        return generatedBy;
    }

    /**
     * Returns a string representation of the ReportHeader, including the generation timestamp and the user responsible for generating the report.
     * @return a string representation of the ReportHeader
     */
    @Override
    public String toString() {
        return String.format("ReportHeader{ generatedAt= %s, generatedBy= %s }" , generatedAt, generatedBy);
    }

    /**
     * Checks if this ReportHeader is equal to another object. Two ReportHeader objects are considered equal if they have the same generation timestamp and the same user responsible for generating the report.
     * @param o the object to compare with this ReportHeader
     * @return true if the specified object is equal to this ReportHeader, false otherwise
     */
    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (o == null || getClass() != o.getClass()) return false;
        ReportHeader that = (ReportHeader) o;
        return generatedAt.equals(that.generatedAt) && generatedBy.equals(that.generatedBy);
    }

    /**
     * Returns a hash code value for the ReportHeader, which is computed based on the generation timestamp and the user responsible for generating the report. This method is consistent with the equals method, meaning that if two ReportHeader objects are equal according to the equals method, they will have the same hash code.
     * @return a hash code value for this ReportHeader
     */
    @Override
    public int hashCode() {
        int result = generatedAt.hashCode();
        result = 31 * result + generatedBy.hashCode();
        return result;
    }
}
