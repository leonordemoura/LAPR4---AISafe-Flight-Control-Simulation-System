package aiSafe.reportGeneration.domain;

import aiSafe.aircontrolarea.domain.AreaCode;
import aiSafe.usermanagement.domain.Email;

import java.time.LocalDateTime;
import java.time.YearMonth;
import java.util.EnumMap;
import java.util.List;
import java.util.Map;

/**
 * DDD Factory responsible for assembling a fully-initialised {@link Report} aggregate root.
 *
 * <p>The factory hides the complexity of wiring the right {@link ReportDataCollector}
 * for each {@link ReportType} and delegates section generation to it, keeping the
 * domain aggregate free of infrastructure concerns.</p>
 *
 * <p>New report types require only a new {@link ReportDataCollector} implementation
 * registered in this factory — no other change is needed (Open/Closed Principle).</p>
 */
public class ReportFactory {

    /** Registry of ReportDataCollectors, keyed by the ReportType they support.
     * This allows the factory to delegate section generation without hardcoding
     * any type-specific logic, keeping it open for extension and closed for modification.
     */
    private final Map<ReportType, ReportDataCollector> collectors;

    /**
     * Initializes the factory with a map of ReportDataCollectors. Each collector must support a unique ReportType.
     * @param collectors a non-empty map of ReportDataCollectors, keyed by their supported ReportType (never {@code null} or empty)
     */
    public ReportFactory(final Map<ReportType, ReportDataCollector> collectors) {
        if (collectors == null || collectors.isEmpty()) {
            throw new IllegalArgumentException("ReportFactory requires at least one ReportDataCollector.");
        }
        this.collectors = new EnumMap<>(collectors);
    }

    /**
     * Creates a new report for the given type, period, and area code, generated by the specified user.
     * @param reportType the type of report to create (e.g. "safety", "compliance") (never {@code null})
     * @param period the month/year the report covers (never {@code null})
     * @param areaCode the air-control area code (never {@code null} or blank)
     * @param generatedByUser the email of the user generating the report (never {@code null})
     * @return a fully-initialised Report aggregate ready for rendering
     * @throws IllegalArgumentException if any argument is invalid or if no collector is registered for the given report type
     */
    public Report create(final ReportType reportType, final YearMonth period, final AreaCode areaCode, final Email generatedByUser) {

        if (reportType == null) throw new IllegalArgumentException("Report type cannot be null.");
        if (period == null) throw new IllegalArgumentException("Period cannot be null.");
        if (generatedByUser == null) throw new IllegalArgumentException("User email cannot be null.");

        final ReportDataCollector collector = collectors.get(reportType);
        if (collector == null) {
            throw new IllegalArgumentException("The report type '" + reportType + "' is not yet implemented or registered.");
        }

        final List<ReportSection> sections = collector.collect(period, areaCode);
        if (sections == null || sections.isEmpty()) {
            throw new IllegalStateException("Collector for " + reportType + " produced no sections.");
        }

        final ReportTitle title = buildTitle(reportType, period, areaCode);
        final ReportPeriod rPeriod = ReportPeriod.valueOf(period);
        final ReportHeader header = ReportHeader.valueOf(LocalDateTime.now(), generatedByUser.toString());

        return Report.create(title, rPeriod, header, reportType, areaCode, sections);
    }

    /**
     * Builds a report title based on the report type, period, and area code.
     * @param type the type of report (e.g. "safety", "compliance") (never {@code null})
     * @param period the month/year the report covers (never {@code null})
     * @param areaCode the air-control area code (never {@code null} or blank)
     * @return a ReportTitle value object combining the type, period, and area code in a human-readable format
     */
    private ReportTitle buildTitle(final ReportType type, final YearMonth period, final AreaCode areaCode) {
        return ReportTitle.valueOf(type + " – " + period + " – " + areaCode.value());
    }
}
